#!/usr/bin/env node
// Generate 400px MoodPals check-in animation frames without modifying original artwork.
// macOS: uses built-in sips. Run: node scripts/generate-mood-preview-frames.cjs
const fs=require('node:fs');
const path=require('node:path');
const cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const moods=['joy','disgust','sadness','anger','fear','tired'];
const manifest=[];
let total=0;
for(const mood of moods){
 const src=path.join(root,'assets','mascot-animations',mood,'ios');
 const out=path.join(root,'assets','mascot-animations',mood,'preview400');
 if(!fs.existsSync(src))throw Error('Missing source directory: '+src);
 fs.mkdirSync(out,{recursive:true});
 const frames=fs.readdirSync(src).filter(f=>/^frame_\d+\.png$/.test(f)).sort();
 if(!frames.length)throw Error('No frames found: '+src);
 const entries=[];
 for(const name of frames){
  const input=path.join(src,name),output=path.join(out,name);
  if(!fs.existsSync(output)||fs.statSync(output).mtimeMs<fs.statSync(input).mtimeMs){
   // -Z fits within a 400 x 400 box and preserves aspect ratio and PNG alpha.
   cp.execFileSync('sips',['-s','format','png','-Z','400',input,'--out',output],{stdio:'ignore'});
  }
  entries.push("  require('./assets/mascot-animations/"+mood+"/preview400/"+name+"')");
  total++;
 }
 manifest.push(' '+mood+': [\n'+entries.join(',\n')+'\n ]');
 console.log(mood+': '+frames.length+' preview frames');
}
const output="import type {ImageSourcePropType} from 'react-native';\n"+
"// Auto-generated by scripts/generate-mood-preview-frames.cjs; do not edit.\n"+
"export const MASCOT_PREVIEW_FRAMES:Record<'joy'|'disgust'|'sadness'|'anger'|'fear'|'tired',ImageSourcePropType[]> = {\n"+
manifest.join(',\n')+"\n};\n";
fs.writeFileSync(path.join(root,'MascotPreviewAssets.ts'),output);
console.log('Generated '+total+' 400px frames and MascotPreviewAssets.ts');
console.log('Next: connect the preview frames in SuperdotMascot, then verify and commit generated assets.');
